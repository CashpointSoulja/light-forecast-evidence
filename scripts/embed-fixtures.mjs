// Embeds fixtures/*.csv into src/generated/fixtures.ts so the Worker, tests and evals read identical bytes.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../fixtures/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".csv")).sort();
const body = files.map((f) => `  ${JSON.stringify(f.replace(/\.csv$/, ""))}: ${JSON.stringify(readFileSync(new URL(f, dir), "utf8"))},`).join("\n");
const out = `// Generated by scripts/embed-fixtures.mjs from fixtures/*.csv. Synthetic data only. Do not edit.\nexport const FIXTURES: Record<string, string> = {\n${body}\n};\n`;
const target = new URL("../src/generated/fixtures.ts", import.meta.url);
if (process.argv.includes("--check")) {
  const cur = readFileSync(target, "utf8");
  if (cur !== out) { console.error("src/generated/fixtures.ts is out of date: run npm run fixtures"); process.exit(1); }
  console.log("fixtures in sync");
} else { writeFileSync(target, out); console.log(`embedded ${files.length} fixtures`); }
